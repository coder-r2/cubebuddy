// Alg database types (SPEC §7.1).

export type AlgSetId = 'f2l' | 'f2l-advanced' | 'oll-2look' | 'pll-2look' | 'oll' | 'pll' | 'ortega' | 'cll';

/**
 * What an alg achieves, used for verification (SPEC §6.5) and recognition:
 * - f2l-pair: solves one F2L pair, keeping the cross and the other slots;
 * - eo: orients the last-layer edges; oll: orients the whole last layer;
 * - cpll: permutes the last-layer corners; pll: solves the cube (with a final AUF);
 * - ortega-oll: orients the 2x2 top face; pbl / cll: solves the 2x2 (with final U/D turns).
 */
export type Goal = 'f2l-pair' | 'eo' | 'oll' | 'cpll' | 'pll' | 'ortega-oll' | 'pbl' | 'cll';

export type Slot = 'FR' | 'FL' | 'BL' | 'BR';

export type DiagramKind = 'oll' | 'pll' | 'f2l' | 'oll-2x2' | 'cll' | 'pbl';

export interface AlgCase {
  id: string;
  name: string;
  group?: string;
  /** Main alg first, then up to two alternatives (D-016). */
  algs: [string, ...string[]];
  /** Overrides the set's goal (the 2-look sets mix goals). */
  goal?: Goal;
  /** Overrides the set's diagram style. */
  diagram?: DiagramKind;
  /** Target slot for F2L cases (default FR). */
  slot?: Slot;
  /** Algs generated by the engine's search rather than collected from references (D-077). */
  generated?: boolean;
}

export interface AlgSet {
  id: AlgSetId;
  puzzle: '3x3x3' | '2x2x2';
  name: string;
  description: string;
  goal: Goal;
  diagram: DiagramKind;
  /** cubing.js stickering preset for the 3D demo. */
  stickering: string;
  cases: AlgCase[];
}
