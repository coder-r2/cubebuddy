import { writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { F2L_CASES } from '../data/algs/f2l';
import { ORTEGA_CASES } from '../data/algs/ortega';
import type { AlgCase, Slot } from '../data/algs/types';
import { caseBase, caseState, solvesWith } from './cases';
import { CORNER_FACELETS, CORNER_NAMES, EDGE_NAMES, readPieces } from './cubies';
import { applyMoves, isSolved, type Facelets } from './facelets';
import { stuckF2LStates } from './f2lCases';
import { formatAlg, parseAlg, type Move } from './notation';
import { conjugate, solveNextPair } from './solvers';
import { solve2x2RUF } from './twoByTwo';

/*
 * Offline generator for the engine-generated alg sets (D-077). Skipped unless GENERATE_ALGS=1:
 *   GENERATE_ALGS=1 npx vitest run src/engine/generate.test.ts
 * The committed output is verified by algDatabase.test.ts like every other set.
 */

const env = (globalThis as { process?: { env: Record<string, string | undefined> } }).process?.env ?? {};
const AUFS = ['', 'U', "U'", 'U2'].map(parseAlg);

function writeCases(file: string, exportName: string, header: string, cases: AlgCase[]) {
  const body = cases.map((c) => `  ${JSON.stringify(c)},`).join('\n');
  writeFileSync(
    new URL(`../data/algs/${file}`, import.meta.url),
    `import type { AlgCase } from './types';\n\n${header}\n\nexport const ${exportName}: AlgCase[] = [\n${body}\n];\n`,
  );
}

const cornerKey = (s: Facelets) =>
  CORNER_FACELETS.flat()
    .map((i) => s[i])
    .join('');

/** Shortest ⟨R,U,F⟩ alg solving `state` up to a final U turn, over all pre-AUFs (pre-AUF not included). */
function bestCllAlg(state: Facelets): Move[] {
  let best: Move[] | null = null;
  for (const auf of AUFS) {
    let moves = solve2x2RUF(applyMoves(state, auf));
    if (moves.at(-1)?.family === 'U') moves = moves.slice(0, -1);
    if (!best || moves.length < best.length) best = moves;
  }
  return best!;
}

describe.skipIf(!env.GENERATE_ALGS)('generate alg sets', () => {
  it('CLL', () => {
    // Every top-layer state with the bottom layer solved: closure under U, Sune and two corner swaps.
    const generators = [
      'U',
      "R U R' U R U2 R'",
      "R U R' U' R' F R2 U' R' U' R U R' F'",
      "F R U' R' U' R U R' F' R U R' U' R' F R F'",
    ].map(parseAlg);
    const seen = new Map<string, Facelets>([[cornerKey(caseBase()), caseBase()]]);
    const queue = [caseBase()];
    while (queue.length) {
      const s = queue.shift()!;
      for (const g of generators) {
        const next = applyMoves(s, g);
        const k = cornerKey(next);
        if (!seen.has(k)) {
          seen.set(k, next);
          queue.push(next);
        }
      }
    }
    expect(seen.size).toBe(24 * 27);

    const ctx = { goal: 'cll' as const, puzzle: '2x2x2' as const };
    const shapes = ORTEGA_CASES.filter((c) => c.goal === 'ortega-oll');
    const cases: AlgCase[] = [];
    const counters: Record<string, number> = {};
    for (const state of seen.values()) {
      if (AUFS.some((auf) => isSolved(applyMoves(state, auf), true))) continue;
      if (cases.some((c) => solvesWith(state, parseAlg(c.algs[0]), ctx))) continue;
      const shape =
        shapes.find((c) => solvesWith(state, parseAlg(c.algs[0]), { goal: 'ortega-oll', puzzle: '2x2x2' }))
          ?.name ?? 'Oriented';
      counters[shape] = (counters[shape] ?? 0) + 1;
      const n = counters[shape];
      cases.push({
        id: `cll-${shape.toLowerCase()}-${n}`,
        name: `${shape} ${n}`,
        group: shape,
        algs: [formatAlg(bestCllAlg(state))],
        generated: true,
      });
    }
    expect(cases).toHaveLength(42);
    const order = ['Oriented', 'Sune', 'Antisune', 'H', 'Pi', 'U', 'T', 'L'];
    cases.sort(
      (a, b) =>
        order.indexOf(a.group!) - order.indexOf(b.group!) ||
        a.id.localeCompare(b.id, 'en', { numeric: true }),
    );
    writeCases(
      'cll.ts',
      'CLL_CASES',
      '// CLL (42): generated by the engine — optimal ⟨R, U, F⟩ algs, grouped by top-face shape (D-077). Do not edit by hand;\n// regenerate with GENERATE_ALGS=1 npx vitest run src/engine/generate.test.ts',
      cases,
    );
  }, 600_000);

  it('F2L advanced', () => {
    const cases: AlgCase[] = [];
    const Y: Record<Exclude<Slot, 'FR'>, string> = { FL: "y'", BL: 'y2', BR: 'y' };

    // Per-slot variants: the basic case moved to another slot, solved without rotations.
    for (const slot of ['FL', 'BL', 'BR'] as const) {
      for (const basic of F2L_CASES) {
        // A reference alg without slices/rotations can be relabelled into the slot; it sets up the same situation there.
        const reference = basic.algs.find((a) => /^[URFDLBurfdlb'2 ]+$/.test(a))!;
        const moved = formatAlg(conjugate(parseAlg(reference), parseAlg(Y[slot])));
        const state = caseState(moved);
        // Main: the familiar front-right alg done from the other slot. Alternative: shortest with U and the
        // slot's own two faces (searched in the target-slot frame, so R/F there are the slot's faces).
        const step = solveNextPair(state, 0, 'rotationless', slot, [1, 0, 2])!;
        const shortest = formatAlg(step.moves);
        const algs: [string, ...string[]] = shortest === moved ? [moved] : [moved, shortest];
        cases.push({
          id: `f2l-adv-${slot.toLowerCase()}-${basic.id.slice(4)}`,
          name: `${basic.name} (${slot})`,
          group: `${slot} slot`,
          slot,
          algs,
          generated: true,
        });
      }
    }

    // Stuck pieces: one FR piece trapped in another slot.
    const slotOf: Record<string, string> = { DLF: 'FL', DBL: 'BL', DRB: 'BR' };
    stuckF2LStates().forEach((state, i) => {
      // No D turns (they move the cross); shortest without rotations, then the front-right style version.
      const step = solveNextPair(state, 0, 'rotationless', 'FR', [1, 0, 2, 4, 5])!;
      const fr = solveNextPair(state, 0, 'front-right', 'FR')!;
      const main = formatAlg(step.moves);
      const alt = formatAlg(fr.moves);
      const { corners, edges } = readPieces(state);
      const cornerAt = CORNER_NAMES[Math.floor(corners[4]! / 3)]!;
      const edgeAt = EDGE_NAMES[edges[8]! >> 1]!;
      const where = cornerAt.startsWith('D')
        ? `Corner stuck in ${slotOf[cornerAt]}`
        : `Edge stuck in ${edgeAt}`;
      cases.push({
        id: `f2l-adv-stuck-${i + 1}`,
        name: `${where} (${i + 1})`,
        group: 'Stuck pieces',
        algs: alt === main ? [main] : [main, alt],
        generated: true,
      });
    });

    expect(cases).toHaveLength(41 * 3 + 36);
    writeCases(
      'f2lAdvanced.ts',
      'F2L_ADVANCED_CASES',
      '// F2L Advanced: the 41 cases in the other three slots plus "stuck piece" cases, with optimal rotationless algs\n// generated by the engine (D-015, D-077). Do not edit by hand; regenerate with\n// GENERATE_ALGS=1 npx vitest run src/engine/generate.test.ts',
      cases,
    );
  }, 600_000);
});
